#Bài tập 1
import numpy as np
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score

np.random.seed(42)
n = 200
bmi = np.random.normal(25, 5, n).reshape(-1,1) #BMI trung bình là 25, độ lệch chuẩn là 5
#Logic cần hiểu: BMI càng cao thì tỷ lệ mắc bệnh càng cao
xac_suat = 1/(1+np.exp(-(0.8 * (bmi.flatten() - 26))))
mac_benh = (np.random.rand(n) < xac_suat).astype(int)
x_train, x_test, y_train, y_test = train_test_split(bmi, mac_benh, test_size=0.2, random_state=42)
log_reg = LogisticRegression()
log_reg.fit(x_train, y_train)
y_pred = log_reg.predict(x_test)

acc = accuracy_score(y_test, y_pred)
print(f"Độ chính xác của mô hình: {acc * 100:.2f}%")
#Giảm hệ số góc trong hàm sinh xác suất từ 0.8 xuống 0.15
xac_suat_kt = 1/(1+np.exp(-(0.15 * (bmi.flatten() - 26))))
mac_benh_kt = (np.random.rand(n) < xac_suat_kt).astype(int)
x_train_kt, x_test_kt, y_train_kt, y_test_kt = train_test_split(bmi, mac_benh_kt, test_size=0.2, random_state=42)
log_reg_kt = LogisticRegression()
log_reg_kt.fit(x_train_kt, y_train_kt)
y_pred_kt = log_reg.predict(x_test_kt)

acc_kt = accuracy_score(y_test_kt, y_pred_kt)
print(f"Độ chính xác của mô hình: {acc_kt * 100:.2f}%")

"""**Nhận xét: Khi độ nhiễu tăng lên thì độ chính xác giảm xuống.**."""

