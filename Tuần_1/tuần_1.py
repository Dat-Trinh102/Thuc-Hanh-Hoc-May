#Bài tập 2
import numpy as np
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, confusion_matrix

np.random.seed(42)
n = 200
bmi = np.random.normal(25, 5, n).reshape(-1,1) #BMI trung bình là 25, độ lệch chuẩn là 5
#Logic cần hiểu: BMI càng cao thì tỷ lệ mắc bệnh càng cao
xac_suat = 1/(1+np.exp(-(0.8 * (bmi.flatten() - 26))))
mac_benh = (np.random.rand(n) < xac_suat).astype(int)
x_train, x_test, y_train, y_test = train_test_split(bmi, mac_benh, test_size=0.2, random_state=42)
log_reg = LogisticRegression()
log_reg.fit(x_train, y_train)
y_prob = log_reg.predict_proba(x_test)[:,1]
y_pred = log_reg.predict(x_test)

acc = accuracy_score(y_test, y_pred)
cm = confusion_matrix(y_test, y_pred)
print(f"Độ chính xác của mô hình: {acc * 100:.2f}%")
print(f"Ma trận nhầm lẫn: {cm}")

plt.figure(figsize=(8,5))
plt.scatter(bmi, mac_benh, color='blue', alpha=0.5, label='Dữ liệu thực tế')

x_range = np.linspace(bmi.min(), bmi.max(), 300).reshape(-1,1)
y_range_prob = log_reg.predict_proba(x_range)[:,1]
plt.plot(x_range, y_range_prob, color='red', linewidth=2, label='Đường hồi quy Logistic')
plt.axhline(y=0.5, color='green', linestyle='--', label='Ngưỡng phân loại 0.5')
plt.title('Dự đoán khả năng mắc bệnh dựa trên chỉ số BMI')
plt.xlabel('BMI')
plt.ylabel('Tỷ lệ mắc bệnh')
plt.legend()
plt.grid(True)
plt.show()

