from sklearn.datasets import load_iris
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.pipeline import make_pipeline
from sklearn.svm import SVC
from sklearn.metrics import accuracy_score, classification_report

iris = load_iris()
X, y = iris.data, iris.target

splits = [
    ("80/20 (random_state=42)", 0.2, 42),
    ("70/30 (random_state=42)", 0.3, 42),
    ("60/40 (random_state=42)", 0.4, 42),
    ("80/20 (random_state=123)", 0.2, 123),
]

for label, test_sz, seed in splits:
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=test_sz, random_state=seed, stratify=y
    )

    svm_clf = make_pipeline(StandardScaler(), SVC(kernel="rbf", C=1.0, random_state=seed))
    svm_clf.fit(X_train, y_train)
    y_pred = svm_clf.predict(X_test)

    acc = accuracy_score(y_test, y_pred)
    print(f"=== Cách chia: {label} ===")
    print(f"Accuracy: {acc:.4f}")
    print(classification_report(y_test, y_pred, target_names=iris.target_names))

