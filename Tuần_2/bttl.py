#Bài tập 1
import numpy as np
import pandas as pd
from sklearn.datasets import load_iris
from sklearn.model_selection import train_test_split
from sklearn.neighbors import KNeighborsClassifier
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score, confusion_matrix, classification_report
import matplotlib.pyplot as plt
import seaborn as sns

iris = load_iris()
x = iris.data
y = iris.target

x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=0.2, random_state=42, stratify=y)

k_values = [1, 3, 5, 7, 9, 11, 15]
print("Kết quả đánh giá mô hình cho từng giá trị k (chưa chuẩn hóa):")
for k in k_values:
    knn_model = KNeighborsClassifier(n_neighbors=k, metric='euclidean')
    knn_model.fit(x_train, y_train)
    y_pred = knn_model.predict(x_test)
    print(f"K = {k}:")
    print("Độ chính xác:", accuracy_score(y_test, y_pred))

scaler = StandardScaler()
x_train_scaled = scaler.fit_transform(x_train)
x_test_scaled = scaler.transform(x_test)
print("Kết quả đánh giá mô hình cho từng giá trị k (đã chuẩn hóa):")
best_k = None
best_acc = -1.0
for k in k_values:
    model_sau = KNeighborsClassifier(n_neighbors=k, metric='euclidean')
    model_sau.fit(x_train_scaled, y_train)
    y_pred_sau = model_sau.predict(x_test_scaled)
    acc_sau = accuracy_score(y_test, y_pred_sau)
    print(f"K = {k}:")
    print("Độ chính xác:", acc_sau)
    if acc_sau > best_acc:
        best_acc = acc_sau
        best_k = k
print("Kết quả tốt nhất:")
print(f"K = {best_k}:")
print("Độ chính xác:", best_acc)

metrics_config = [("euclidean", {}), ("manhattan", {}), ("minkowski", {"p": 3})]
print(f"So sánh độ đo khoảng cách với k = {best_k}")
best_model = None
best_y_pred = None
best_metric_acc = -1.0
best_metric_name = ""
for metric_name, kw in metrics_config:
  clf = KNeighborsClassifier(n_neighbors=best_k, metric=metric_name, **kw)
  clf.fit(x_train_scaled, y_train)
  pred = clf.predict(x_test_scaled)
  acc = accuracy_score(y_test, pred)
  print(f"Metric = {metric_name:10s} {kw}")
  print(f"Độ chính xác: {acc:.4f}")
  if acc > best_metric_acc:
    best_metric_acc = acc
    best_model = clf
    best_y_pred = pred
    best_metric_name = metric_name
print("Báo cáo phân loại tốt nhất (K={best_k}, Metric={best_metric_name}):")
print(classification_report(y_test, best_y_pred))

confusion_mat = confusion_matrix(y_test, best_y_pred)
plt.figure(figsize=(7, 5))
sns.heatmap(confusion_mat, annot=True, fmt='d', cmap='Blues', xticklabels=iris.target_names, yticklabels=iris.target_names)
plt.xlabel('Dự đoán')
plt.ylabel('Thực tế')
plt.title(f"Ma trận nhầm lẫn KNN (K={best_k}, metric={best_metric_name})")
plt.tight_layout()
plt.show()

